cepath = fullfile(fileparts(fileparts(mfilename('fullpath'))), 'CompEcon');
if ~exist(fullfile(cepath, 'CEtools'), 'dir')
    error('startup:CompEconMissing', ...
        ['CompEcon not found at %s. It is NOT redistributed with this ' ...
         'package. Download it from ' ...
         'http://www4.ncsu.edu/~pfackler/compecon/toolbox.html and place the ' ...
         'CompEcon folder next to the model folders, or add its CEtools ' ...
         'directory to the MATLAB path. See README.pdf.'], cepath);
end
ws = warning('off', 'MATLAB:dispatcher:nameConflict');
addpath(fullfile(cepath, 'CEtools'), '-end');
warning(ws);
